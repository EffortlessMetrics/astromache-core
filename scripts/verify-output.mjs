import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
const html = await readFile("consumers/neutral/dist/index.html", "utf8");
assert.match(html, /<title>Neutral publication<\/title>/);
const openingHtml = html.match(/<html\b[^>]*>/)?.[0];
assert.ok(openingHtml, "Missing root html element");
assert.match(openingHtml, /\sdata-publication="neutral"(?=\s|>)/);
assert.match(openingHtml, /\slang="en"(?=\s|>)/);
assert.doesNotMatch(html, /invalid-override/);
assert.match(html, /href="https:\/\/neutral.example\/"/);
assert.match(html, /href="#main"/);
assert.match(html, /<main id="main" tabindex="-1">/);
assert.doesNotMatch(html, /<script\b/);
const profile = await readFile("consumers/neutral/dist/profile/index.html", "utf8");
assert.match(profile, /id="profile-title"[^>]*>Example author<\/h1>/);
assert.match(profile, /id="about"[^>]*aria-labelledby="profile-title"/);
assert.match(profile, /id="speaking"[^>]*aria-labelledby="profile-speaking-title"/);
assert.match(profile, /id="follow"[^>]*aria-labelledby="profile-follow-title"/);
assert.match(profile, /href="https:\/\/profiles\.example\/person\/" rel="me"/);
assert.match(profile, /href="\/talk\/"/);
assert.doesNotMatch(profile, /Steven Zimmerman|effortlesssteven\.com|profile\.jpg/);
const minimalProfile = await readFile("consumers/neutral/dist/profile-minimal/index.html", "utf8");
assert.match(minimalProfile, /Example &amp; author/);
assert.doesNotMatch(minimalProfile, /id="speaking"|id="follow"|class="profile-portrait"|<script\b/);
const receipt = { neutral: { htmlBytes: Buffer.byteLength(html) } };
await writeFile(".qualification-output.json", JSON.stringify(receipt, null, 2));
console.log("Neutral document output", JSON.stringify(receipt));
